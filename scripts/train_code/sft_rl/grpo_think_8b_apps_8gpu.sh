# Qwen3-8B (think) → GRPO on APPS (8-GPU).
# Same data/update as the previous 4gpu recipe: train_bs=32, n=4, 50 steps.
# 8-GPU layout mirrors scripts/rl/qwen3_8b_think/grpo_think_8b_omr_int_8gpu_*:
#   rollout4+train4 util budgeting, actor offload, generate pack ~2×max_model_len.
#
# Final ckpt at global_step_50 (merge FSDP → HF, then 3 code think evals).

BASE_DIR=${BASE_DIR:-${SLURM_SUBMIT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}}
